"""Write sql/02_load_data.sql: INSERT statements for every raw file.

The AP export is inserted exactly as exported (text with $, commas, spaces and
three date formats) so that all cleaning is done in SQL.
Usage:  python python/make_load_sql.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW, REF, OUT = ROOT / "data" / "raw", ROOT / "data" / "reference", ROOT / "sql" / "02_load_data.sql"
AS_OF = "2026-09-30"
TAX_RATES = {"ON": 0.13, "QC": 0.14975, "BC": 0.12, "AB": 0.05}


def lit(v, keep_blank=False):
    """Python value -> SQL literal. Blank cells become NULL unless keep_blank."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "NULL"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return repr(round(float(v), 5)).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)
    s = str(v)
    if s == "" and not keep_blank:
        return "NULL"
    return "'" + s.replace("'", "''") + "'"


def insert(table, cols, rows, keep_blank=False):
    values = ",\n".join("    (" + ", ".join(lit(v, keep_blank) for v in r) + ")" for r in rows)
    return f"INSERT INTO recon.{table} ({', '.join(cols)}) VALUES\n{values};\n"


def main():
    vendors = pd.read_excel(RAW / "01_vendor_master.xlsx")
    pos = pd.read_csv(RAW / "02_purchase_orders.csv")
    ap = pd.read_csv(RAW / "03_ap_invoices_export.csv", dtype=str, keep_default_na=False)
    pay = pd.read_csv(RAW / "04_bank_payments.csv")
    mp = pd.read_excel(RAW / "05_app_doctype_vendor_map.xlsx")
    aliases = pd.read_csv(REF / "vendor_aliases.csv")

    ap_rows = [[i + 1, *r] for i, r in enumerate(ap[["Invoice #", "Vendor", "PO", "Invoice Date", "Net Amount",
                                                    "Tax", "Invoice Total", "Currency"]].values.tolist())]
    parts = [
        "/* 02_load_data.sql – generated by python/make_load_sql.py. Run after 01_create_tables.sql. */\n",
        "SET NOCOUNT ON;\n",
        insert("stg_vendors", list(vendors.columns), vendors.values.tolist()),
        insert("stg_purchase_orders", list(pos.columns), pos.values.tolist()),
        insert("stg_ap_invoices", ["SourceRow", "InvoiceNo", "Vendor", "PO", "InvoiceDate", "NetAmount",
                                   "Tax", "InvoiceTotal", "Currency"], ap_rows, keep_blank=True),
        insert("stg_bank_payments", list(pay.columns), pay.values.tolist()),
        insert("stg_app_doc_map", list(mp.columns), mp.values.tolist()),
        insert("ref_vendor_aliases", ["AliasKey", "VendorID"], aliases.values.tolist()),
        insert("ref_tax_rates", ["Province", "TaxRate"], [[k, v] for k, v in TAX_RATES.items()]),
        insert("config", ["AsOfDate"], [[AS_OF]]),
        "GO\n",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(vendors)} vendors, {len(pos)} POs, {len(ap)} invoices, "
          f"{len(pay)} payments, {len(mp)} map rows, {len(aliases)} aliases")


if __name__ == "__main__":
    main()
